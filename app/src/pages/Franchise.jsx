// Tries the supplied photo first, swaps to the fallback once if it is missing.
function CardImg({ src, fb, alt }) {
  return (
    <img
      className="why__img"
      src={src}
      alt={alt}
      width="640"
      height="400"
      loading="lazy"
      decoding="async"
      onError={(e) => {
        if (e.currentTarget.dataset.fb) return
        e.currentTarget.dataset.fb = '1'
        e.currentTarget.src = fb
      }}
    />
  )
}

